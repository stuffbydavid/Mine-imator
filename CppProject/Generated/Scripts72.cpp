					sReal(view_control_move_distance) += ((vec2_length(vecmouse) / veclen) * len * vecdot) * .05 * sReal(dragger_multiplier);
					snapval = ((sReal(dragger_snap) > 0) ? sReal(setting_snap_size_scale) : snap_min);
